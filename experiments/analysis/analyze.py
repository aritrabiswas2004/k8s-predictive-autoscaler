# ---------------------------------------------------------------- formatting

def fmt(stat, digits=1, pct=False, unit=""):
    if stat.n == 0:
        return "–"
    k = 100 if pct else 1
    m = f"{stat.mean * k:.{digits}f}"
    if stat.half is None:
        return f"{m}{unit}"
    return f"{m} ± {stat.half * k:.{digits}f}{unit}"


def col(rows, key):
    return ev.mean_ci([r.get(key) for r in rows])


def table(header, body):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" if i == 0 else "---:" for i in range(len(header))) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(out)


