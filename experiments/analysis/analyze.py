# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--runs", nargs="+", default=[str(REPO / "experiments/results/runs")])
    ap.add_argument("--out", default=str(REPO / "docs"))
    ap.add_argument("--csv", default=str(REPO / "experiments/results/analysis/runs.csv"))
    ap.add_argument("--seed", type=int, default=1, help="repetition shown in the timelines")
    a = ap.parse_args()

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    style(plt)

    runs = []
    for base in a.runs:
        for d in sorted(Path(base).glob("*/")):
            run = ev.load_run(d)
            if run:
                run["row"] = ev.run_row(run)
                runs.append(run)
    rows = [r["row"] for r in runs]
    print(f"{len(rows)} finished runs", file=sys.stderr)
    if not rows:
        raise SystemExit("no finished runs under " + " ".join(a.runs))

    out, img = Path(a.out), Path(a.out) / "img"
    img.mkdir(parents=True, exist_ok=True)
    ev.write_csv(rows, Path(a.csv))
    bt_path = REPO / "experiments/results/backtest/backtest.json"
    backtest = json.loads(bt_path.read_text())["summary"] if bt_path.exists() else {}
    (out / "results-tables.md").write_text(tables(rows, backtest))
    written = [a.csv, out / "results-tables.md"]

    if any(r["grid"] == "main" for r in rows):
        frontier_figure(rows, img / "frontier.png", plt)
        written.append(img / "frontier.png")
    if any(r["grid"] == "sweep" for r in rows):
        sweep_figure(rows, img / "sweep.png", plt)
        written.append(img / "sweep.png")
    live = []
    for grid, w in sorted({(r["meta"]["grid"], r["meta"]["workload"]) for r in runs
                           if r["meta"]["grid"] in ("main", "smoke")}):
        rep = [r for r in runs if (r["meta"]["grid"], r["meta"]["workload"]) == (grid, w)
               and r["meta"]["seed"] == a.seed]
        if rep:
            name = "smoke" if grid == "smoke" else w
            p = img / f"timeline-{name}.png"
            timeline_figure(rep, name, p, plt)
            written.append(p)
            live += [r for r in rep if r["meta"]["arm"] == "d"]
    if any(r["meta"]["grid"] == "main" for r in live):
        live = [r for r in live if r["meta"]["grid"] == "main"]
    if live:
        forecast_figure(live, img / "forecast-live.png", plt)
        written.append(img / "forecast-live.png")
    for p in written:
        print(f"wrote {p}", file=sys.stderr)


if __name__ == "__main__":
    main()
